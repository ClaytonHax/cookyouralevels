import { Sparkles, User } from 'lucide-react'
import { getSubject } from '../../lib/subjects'
import { cn } from '../../lib/cn'
import type { SubjectStats } from '../dashboard/useDashboardData'
import { daysUntil } from '../dashboard/examDate'
import type { SessionCode } from '../../types/content'

/** Non-interactive sample of the future coach, personalised with the student's real weakest topics. No AI runs here. */
export default function CoachPreview({ stats, year, session }: { stats: SubjectStats[]; year?: number; session?: SessionCode }) {
  const weak = stats
    .filter((s) => s.weakest)
    .sort((a, b) => a.weakest!.readiness.pct - b.weakest!.readiness.pct)
    .slice(0, 3)
  const days = year && session ? daysUntil(year, session) : null
  const real = weak.length > 0
  const items = real
    ? weak.map((s, i) => ({ sub: getSubject(s.id)!, topic: s.weakest!.topic.name, mins: [40, 30, 25][i] }))
    : [
        { sub: getSubject('mathematics')!, topic: 'Differentiation', mins: 40 },
        { sub: getSubject('physics')!, topic: 'Circular motion', mins: 30 },
        { sub: getSubject('computer-science')!, topic: 'Recursion', mins: 25 },
      ]

  return (
    <figure className="m-0">
      <div className="card shadow-lift overflow-hidden" role="img" aria-label="Preview of a study coach conversation and daily plan. Example only; the coach is not live yet.">
        <div className="flex items-center gap-2 px-4 py-3 border-b border-border bg-surface-2">
          <Sparkles className="w-4 h-4 text-flame" aria-hidden />
          <span className="font-display font-bold text-sm text-ink">Study Coach</span>
          <span className="ml-auto text-[11px] font-bold px-2 py-0.5 rounded-full bg-flame-soft text-flame-strong dark:text-flame">Preview</span>
        </div>
        <div className="p-4 space-y-4" aria-hidden>
          <div className="flex gap-2.5 justify-end">
            <div className="bg-flame-strong text-white rounded-[14px] rounded-br-md px-3.5 py-2 text-sm max-w-[85%]">What should I do today? I only have an hour and a half.</div>
            <span className="w-7 h-7 rounded-full bg-surface-2 border border-border flex items-center justify-center shrink-0"><User className="w-3.5 h-3.5 text-ink-3" /></span>
          </div>
          <div className="flex gap-2.5">
            <span className="w-7 h-7 rounded-full bg-flame-soft flex items-center justify-center shrink-0"><Sparkles className="w-3.5 h-3.5 text-flame" /></span>
            <div className="bg-surface-2 rounded-[14px] rounded-bl-md px-3.5 py-3 text-sm text-ink-2 max-w-[90%] space-y-3">
              <p>
                {days != null && days > 0 ? `${days} days to go. ` : ''}
                {real ? 'Your lowest-rated topics are the best use of the time. Here is a plan:' : 'Once you rate your syllabus, I will build this from your weakest topics. Here is an example plan:'}
              </p>
              <ol className="space-y-2">
                {items.map((it, i) => (
                  <li key={it.topic + i} className="flex items-center gap-2.5 bg-surface border border-border rounded-control px-3 py-2">
                    <span className={cn('w-2 h-8 rounded-full shrink-0', it.sub.cls.dot)} />
                    <span className="min-w-0 flex-1">
                      <span className="block font-bold text-ink text-[13px] truncate">{it.topic}</span>
                      <span className="block text-[11px] text-ink-3">{it.sub.short} · {i === 0 ? 'Notes, then 5 questions' : i === 1 ? '8 questions' : 'Quick recap'}</span>
                    </span>
                    <span className="text-[11px] font-mono text-ink-3 shrink-0">{it.mins} min</span>
                  </li>
                ))}
              </ol>
            </div>
          </div>
        </div>
      </div>
      <figcaption className="text-xs text-ink-3 mt-2">
        {real ? 'Built from your own weakest topics, but only an illustration. Nothing is generated by AI yet.' : 'Example only. Nothing is generated by AI yet.'}
      </figcaption>
    </figure>
  )
}
